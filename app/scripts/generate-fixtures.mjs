/**
 * Generate synthetic raster-move fixtures + reference masks.
 * Run: node scripts/generate-fixtures.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PNG } from 'pngjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fixturesDir = join(root, 'fixtures');
mkdirSync(fixturesDir, { recursive: true });

function setPx(png, x, y, r, g, b, a = 255) {
  const i = (png.width * y + x) << 2;
  png.data[i] = r;
  png.data[i + 1] = g;
  png.data[i + 2] = b;
  png.data[i + 3] = a;
}

function fillRect(png, x0, y0, x1, y1, r, g, b) {
  for (let y = y0; y <= y1; y++) {
    for (let x = x0; x <= x1; x++) {
      setPx(png, x, y, r, g, b);
    }
  }
}

function drawEllipse(png, cx, cy, rx, ry, r, g, b) {
  for (let y = cy - ry; y <= cy + ry; y++) {
    for (let x = cx - rx; x <= cx + rx; x++) {
      const nx = (x - cx) / rx;
      const ny = (y - cy) / ry;
      if (nx * nx + ny * ny <= 1) setPx(png, x, y, r, g, b);
    }
  }
}

function writeMaskPng(path, mask, width, height) {
  const png = new PNG({ width, height });
  for (let i = 0; i < mask.length; i++) {
    const on = mask[i] > 0;
    const pi = i << 2;
    png.data[pi] = on ? 255 : 0;
    png.data[pi + 1] = on ? 255 : 0;
    png.data[pi + 2] = on ? 255 : 0;
    png.data[pi + 3] = on ? 255 : 0;
  }
  writeFileSync(path, PNG.sync.write(png));
}

// masks generated by matting-mask-iotest.mjs on first run

function makeBedroomCrop() {
  const w = 320;
  const h = 240;
  const png = new PNG({ width: w, height: h });
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const cross = ((Math.floor(x / 12) + Math.floor(y / 12)) & 1) === 0;
      setPx(png, x, y, cross ? 210 : 198, cross ? 185 : 175, cross ? 160 : 150);
    }
  }
  fillRect(png, 0, 0, w - 1, 28, 120, 95, 80);
  drawEllipse(png, 118, 118, 34, 52, 72, 108, 148);
  drawEllipse(png, 118, 72, 18, 20, 92, 128, 168);
  fillRect(png, 98, 148, 138, 198, 68, 102, 142);
  const click = { x: 118, y: 100 };
  return { png, click, name: 'bedroom-crop' };
}

function makeSubwayCrop() {
  const w = 320;
  const h = 240;
  const png = new PNG({ width: w, height: h });
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      setPx(png, x, y, 55, 58, 62);
    }
  }
  fillRect(png, 160, 40, 300, 220, 88, 72, 58);
  drawEllipse(png, 90, 130, 22, 48, 180, 95, 55);
  drawEllipse(png, 90, 78, 14, 16, 195, 110, 70);
  fillRect(png, 72, 168, 108, 210, 175, 88, 50);
  drawEllipse(png, 248, 125, 18, 40, 200, 120, 80);
  const click = { x: 90, y: 120 };
  const negative = [{ x: 248, y: 125 }];
  return { png, click, negative, name: 'subway-crop' };
}

function makeDiptychFull() {
  const w = 640;
  const h = 240;
  const png = new PNG({ width: w, height: h });
  const left = makeBedroomCrop();
  const right = makeSubwayCrop();
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < 320; x++) {
      const i = (left.png.width * y + x) << 2;
      setPx(png, x, y, left.png.data[i], left.png.data[i + 1], left.png.data[i + 2]);
    }
    for (let x = 0; x < 320; x++) {
      const i = (right.png.width * y + x) << 2;
      setPx(png, 320 + x, y, right.png.data[i], right.png.data[i + 1], right.png.data[i + 2]);
    }
  }
  for (let y = 0; y < h; y++) {
    for (let x = 316; x <= 324; x++) {
      setPx(png, x, y, 12, 12, 14);
    }
  }
  return { png, splitX: 320, name: 'diptych-full' };
}

const bedroom = makeBedroomCrop();
const subway = makeSubwayCrop();
const diptych = makeDiptychFull();

writeFileSync(join(fixturesDir, `${bedroom.name}.png`), PNG.sync.write(bedroom.png));

writeFileSync(join(fixturesDir, `${subway.name}.png`), PNG.sync.write(subway.png));

writeFileSync(join(fixturesDir, `${diptych.name}.png`), PNG.sync.write(diptych.png));

const manifest = {
  bedroom: {
    fixture: 'bedroom-crop.png',
    mask: 'bedroom-crop-mask.png',
    click: bedroom.click,
    iouMin: 0.75,
  },
  subway: {
    fixture: 'subway-crop.png',
    mask: 'subway-crop-mask.png',
    click: subway.click,
    negative: subway.negative,
    iouMin: 0.7,
    maxComponents: 3,
  },
  diptych: {
    fixture: 'diptych-full.png',
    splitX: diptych.splitX,
  },
};

writeFileSync(join(fixturesDir, 'manifest.json'), JSON.stringify(manifest, null, 2));
console.log('Fixtures written to', fixturesDir);
